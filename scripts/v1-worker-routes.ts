import { v1Operations } from "../src/v1/operations/index.js";

export type GeneratedWorkerRoute = {
  operationId: string;
  path: string;
  methods: Array<"GET" | "POST">;
  scope: string;
  expensive?: "offers-list" | "search" | "heavy" | "bulk";
};

export function buildWorkerRouteTable(): GeneratedWorkerRoute[] {
  return v1Operations.map((operation) => ({
    operationId: operation.operationId,
    path: operation.path,
    methods: [operation.method],
    scope: operation.scope,
    ...(operation.expensivePolicy
      ? { expensive: operation.expensivePolicy }
      : {}),
  }));
}

export function renderWorkerRouteTable(): string {
  const table = buildWorkerRouteTable();
  return `// Generated by scripts/generate-v1-worker-routes.ts. Do not edit.
// Source of truth: src/v1/operations/index.ts.
import type { ApiScope } from "./types.js";

export type GeneratedV1ExpensivePolicy =
  | "offers-list"
  | "search"
  | "heavy"
  | "bulk";

export type GeneratedV1Route = {
  operationId: string;
  path: string;
  methods: Array<"GET" | "POST">;
  scope: ApiScope;
  expensive?: GeneratedV1ExpensivePolicy;
};

export const generatedV1Routes: GeneratedV1Route[] = ${JSON.stringify(
    table,
    null,
    2,
  )} as GeneratedV1Route[];
`;
}
